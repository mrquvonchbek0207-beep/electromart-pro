const productPhraseMatchers = new Map();

export function localizeProductText(text, lang = "ru") {
  if (typeof text !== "string") return "";
  if (lang === "ru") return text;
  const cacheKey = `${lang}\u0000${text}`;
  if (productTextCache.has(cacheKey)) return productTextCache.get(cacheKey);
  let matchers = productPhraseMatchers.get(lang);
  if (!matchers) {
    const phrases = {
      ...(productPhraseTranslations[lang] || {}),
      ...(contentPhraseTranslations[lang] || {}),
    };
    matchers = Object.keys(phrases)
      .sort((a, b) => b.length - a.length)
      .map((phrase) => [new RegExp(escapeRegExp(phrase), "gi"), phrases[phrase]]);
    productPhraseMatchers.set(lang, matchers);
  }
  if (matchers.length === 0) return text;
  let localized = text;
  for (const [pattern, translation] of matchers) {
    localized = localized.replace(pattern, translation);
  }
  if (productTextCache.size >= 4096) productTextCache.delete(productTextCache.keys().next().value);
  productTextCache.set(cacheKey, localized);
  return localized;
}

