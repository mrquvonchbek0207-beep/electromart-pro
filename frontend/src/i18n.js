const numberLocales = { uz: "uz-UZ", ru: "ru-RU", en: "en-US" };

export function priceInCurrency(priceInRub, lang = "ru") {
  const amountInRub = Number(priceInRub);
  const safeAmount = Number.isFinite(amountInRub) ? amountInRub : 0;
  if (lang === "uz") return Math.round(safeAmount * 140);
  if (lang === "en") return Math.round(safeAmount / 90);
  return Math.round(safeAmount);
}

export function formatPrice(priceInRub, lang = "ru") {
  const amount = Number(priceInRub);
  const safeAmount = Number.isFinite(amount) ? amount : 0;
  if (lang === "uz") {
    const converted = priceInCurrency(safeAmount, lang);
    return `${new Intl.NumberFormat(numberLocales.uz, { maximumFractionDigits: 0 }).format(converted)} so'm`;
  }
  if (lang === "en") {
    const converted = priceInCurrency(safeAmount, lang);
    return `$${new Intl.NumberFormat(numberLocales.en, { maximumFractionDigits: 0 }).format(converted)}`;
  }
  return `${new Intl.NumberFormat(numberLocales.ru, { maximumFractionDigits: 0 }).format(priceInCurrency(safeAmount, lang))} ₽`;
}

export function priceFromCurrency(amount, lang = "ru") {
  const numericAmount = Number(amount);
  if (!Number.isFinite(numericAmount)) return 0;
  if (lang === "uz") return Math.round(numericAmount / 140);
  if (lang === "en") return Math.round(numericAmount * 90);
  return Math.round(numericAmount);
}

export function currencyLabel(lang = "ru") {
  return lang === "uz" ? "so'm" : lang === "en" ? "$" : "₽";
}

export function formatInstallment(priceInRub, lang = "ru") {
  const monthlyPrice = Math.ceil((Number(priceInRub) || 0) / 12);
  const formattedAmount = formatPrice(monthlyPrice, lang);
  if (lang === "uz") return `oyiga ${formattedAmount}dan muddatli to'lov`;
  if (lang === "en") return `from ${formattedAmount}/mo installment`;
  return `от ${formattedAmount}/мес в рассрочку`;
}

