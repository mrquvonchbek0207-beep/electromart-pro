export function translate(language, value) {
  if (typeof value !== "string" || language === "ru") return value;
  const dictionary = translations[language] || translations.ru;
  const normalized = value.replace(/\s+/g, " ").trim();
  const translated = dictionary[normalized];
  if (!translated) {
    const priceFieldLabel = normalized.match(/^(Цена|Старая цена),\s*(₽|so'm|\$)$/);
    if (priceFieldLabel) {
      const labels = language === "uz"
        ? { "Цена": "Narxi", "Старая цена": "Eski narxi" }
        : { "Цена": "Price", "Старая цена": "Old price" };
      return value.replace(normalized, `${labels[priceFieldLabel[1]]}, ${priceFieldLabel[2]}`);
    }
    if (normalized === "Код страны") {
      return value.replace(normalized, language === "uz" ? "Mamlakat kodi" : "Country code");
    }
    const orderTotals = normalized.match(/^(\d+)\s+заказов\s·\s(.+)$/);
    if (orderTotals) {
      const replacement = language === "uz"
        ? `${orderTotals[1]} ta buyurtma · ${orderTotals[2]}`
        : `${orderTotals[1]} orders · ${orderTotals[2]}`;
      return value.replace(normalized, replacement);
    }
    const revenue = normalized.match(/^(.+?)\s·\sобщая сумма$/);
    if (revenue) {
      const replacement = language === "uz" ? `${revenue[1]} · Jami tushum` : `${revenue[1]} · Total revenue`;
      return value.replace(normalized, replacement);
    }
    const inputLabel = normalized.match(/^(Цена товара|Скидка товара|Остаток товара|Удалить товар)\s+(.+)$/);
    if (inputLabel) {
      const labels = language === "uz"
        ? { "Цена товара": "Mahsulot narxi", "Скидка товара": "Mahsulot chegirmasi", "Остаток товара": "Mahsulot qoldig‘i", "Удалить товар": "Mahsulotni o‘chirish" }
        : { "Цена товара": "Product price", "Скидка товара": "Product discount", "Остаток товара": "Product stock", "Удалить товар": "Delete product" };
      return value.replace(normalized, `${labels[inputLabel[1]]} ${inputLabel[2]}`);
    }
    const shownProducts = normalized.match(/^Показано\s+(\d+)\s+из\s+(\d+)\s+товаров$/);
    if (shownProducts) {
      const replacement = language === "uz"
        ? `${shownProducts[1]} / ${shownProducts[2]} ta mahsulot ko‘rsatildi`
        : `Showing ${shownProducts[1]} of ${shownProducts[2]} products`;
      return value.replace(normalized, replacement);
    }
    const stock = normalized.match(/^В наличии:\s*(\d+)\s*шт\.$/);
    if (stock) {
      const replacement = language === "uz" ? `Mavjud: ${stock[1]} dona` : `In stock: ${stock[1]}`;
      return value.replace(normalized, replacement);
    }
    const installment = normalized.match(/^от\s+(.+?)\s*₽\/мес в рассрочку на 12 мес$/);
    if (installment) {
      const replacement = language === "uz"
        ? `12 oyga bo‘lib to‘lash: oyiga ${installment[1]} ₽`
        : `12-month installments: ${installment[1]} ₽/month`;
      return value.replace(normalized, replacement);
    }
    const productCount = normalized.match(/^(\d+)\s+товаров$/);
    if (productCount) return value.replace(normalized, language === "uz" ? `${productCount[1]} ta mahsulot` : `${productCount[1]} products`);
    const rangeCount = normalized.match(/^(\d+)\s+из\s+(\d+)$/);
    if (rangeCount) return value.replace(normalized, `${rangeCount[1]} ${language === "uz" ? "/" : "of"} ${rangeCount[2]}`);
    return localizeProductText(value, language);
  }
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  return `${leading}${translated}${trailing}`;
}

function localizeNode(node, language) {
  if (typeof node === "string") return translate(language, node);
  if (Array.isArray(node)) return Children.toArray(node).map((child) => localizeNode(child, language));
  if (!isValidElement(node)) return node;

  const props = {};
  for (const [key, value] of Object.entries(node.props)) {
    if (key === "children") props.children = localizeNode(value, language);
    else if (key === "value") props[key] = value;
    else if (typeof value === "string") props[key] = translate(language, value);
    else props[key] = value;
  }
  return cloneElement(node, props);
}

export function Localized({ children }) {
  const { language } = useContext(LanguageContext);
  return localizeNode(children, language);
}

export function LanguageSelect({ language, onChange, className = "" }) {
  return createElement(
    "div",
    { className: `language-switcher ${className}`, role: "group", "aria-label": translate(language, "Переключить язык") },
    ...LANGUAGES.map((code) => createElement(
      "button",
      {
        type: "button",
        key: code,
        className: language === code ? "language-active" : "",
        "aria-pressed": language === code,
        onClick: () => onChange(code),
      },
      code.toUpperCase(),
    )),
  );
}
